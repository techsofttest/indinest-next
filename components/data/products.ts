export function priceInRange(priceStr: string, range: string): boolean {
  const num = parseInt(priceStr.replace(/[^0-9]/g, ""), 10);
  if (range === "Under £5,000") return num < 5000;
  if (range === "£5,000 – £10,000") return num >= 5000 && num < 10000;
  if (range === "£10,000 – £20,000") return num >= 10000 && num <= 20000;
  if (range === "Above £20,000") return num > 20000;
  return true;
}

